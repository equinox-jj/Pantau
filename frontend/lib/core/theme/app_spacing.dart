/// 4px-base spacing scale from the Pantau design system.
abstract final class AppSpacing {
  static const double xs2 = 8; // icon gaps, chip dot
  static const double xs = 12; // list gaps, inline
  static const double sm = 14; // card padding
  static const double md = 16; // field gaps
  static const double lg = 20; // stack rhythm
  static const double xl = 26; // screen padding
  static const double xl2 = 32; // section gaps
  static const double xl3 = 44; // min tap target
  static const double xl4 = 56; // control height
}
